// Generates the app's cross-stitch icon data and ornament masks from the Vonica embroidery source
// (identity/…/ikony-12x12.json: 12 rows × 12 chars, "." empty, "X" ink thread, "R" red thread).
//
//   node scripts/generate-stitch-icons.mjs [source.json]
//
// Output:
//   frontend/src/app/shared/icon/stitch-icons.data.ts – icon grids (category ≠ ornament)
//   frontend/public/identity/ornaments/<id>.svg       – ornament masks (category = ornament)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(process.argv[2] ?? path.join(rootDir, 'identity', 'identity-02-12x12', 'ikony-12x12.json'));
const dataFile = path.join(rootDir, 'frontend', 'src', 'app', 'shared', 'icon', 'stitch-icons.data.ts');
const ornamentDir = path.join(rootDir, 'frontend', 'public', 'identity', 'ornaments');

const SIZE = 12;
const CELL = 10;
const INSET = 1.5;
const STROKE = 4.2;
const THREADS = { '.': '0', X: '1', R: '2' };

const collection = JSON.parse(fs.readFileSync(source, 'utf8'));

function encode(item) {
  const ornament = item.category === 'ornament';
  const rows = item.rows;
  const width = rows?.[0]?.length;
  if (!Array.isArray(rows) || (!ornament && (rows.length !== SIZE || width !== SIZE))) {
    throw new Error(`${item.id}: icons must be ${SIZE}×${SIZE}`);
  }
  return rows
    .map((row, y) => {
      if (row.length !== width) throw new Error(`${item.id}: row ${y + 1} has ${row.length} chars, expected ${width}`);
      return [...row]
        .map((ch, x) => {
          if (!(ch in THREADS)) throw new Error(`${item.id}: unknown char "${ch}" at ${x + 1}×${y + 1}`);
          return THREADS[ch];
        })
        .join('');
    })
    .join('');
}

function ornamentSvg(item) {
  const width = item.rows[0].length;
  const parts = [];
  item.rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === '.') return;
      const a = x * CELL + INSET, b = (x + 1) * CELL - INSET, c = y * CELL + INSET, d = (y + 1) * CELL - INSET;
      parts.push(`M${a} ${c}L${b} ${d}M${a} ${d}L${b} ${c}`);
    }),
  );
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width * CELL} ${item.rows.length * CELL}" fill="none" stroke="#000" stroke-width="${STROKE}" stroke-linecap="round"><path d="${parts.join('')}"/></svg>\n`;
}

const icons = collection.items.filter((i) => i.category !== 'ornament');
const ornaments = collection.items.filter((i) => i.category === 'ornament');

const lines = icons.map((i) => `  '${i.id}': '${encode(i)}',`);
fs.writeFileSync(
  dataFile,
  `// GENERATED by scripts/generate-stitch-icons.mjs from ${path.relative(rootDir, source)} – do not edit by hand.
// Grid ${SIZE}×${SIZE} row by row: 0 = empty, 1 = ink thread (currentColor), 2 = red thread (--stitch-accent).
import type { IconName } from './icon.component';

export const STITCH_SIZE = ${SIZE};
export const STITCH_CELL = ${CELL};
export const STITCH_INSET = ${INSET};
export const STITCH_STROKE = ${STROKE};

export const STITCH_GRIDS: Record<IconName, string> = {
${lines.join('\n')}
};
`,
);

fs.mkdirSync(ornamentDir, { recursive: true });
for (const o of ornaments) {
  encode(o);
  fs.writeFileSync(path.join(ornamentDir, `${o.id}.svg`), ornamentSvg(o));
}

console.log(`${icons.length} icons → ${path.relative(rootDir, dataFile)}, ${ornaments.length} ornaments → ${path.relative(rootDir, ornamentDir)}`);
