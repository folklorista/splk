// Converts the local (unversioned) member list dev/local/clenove.tsv into
// frontend/src/app/features/members/data/mock-members.local.ts, which replaces
// the fictional mock members in the `demo` build configuration.
// Both files are git-ignored – real names must never reach the repository.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');

const source = path.resolve(rootDir, process.argv[2] ?? 'dev/local/clenove.tsv');
const target = path.join(rootDir, 'frontend', 'src', 'app', 'features', 'members', 'data', 'mock-members.local.ts');

// Column header → group id (must match frontend/src/app/core/data/mock-groups.ts)
const GROUP_COLUMNS = {
  'výbor': 1,
  'taneční': 2,
  'muzika': 3,
  'kluci': 4,
  'holky': 5,
  'malá vonica': 6,
  'sklad': 7,
};

if (!fs.existsSync(source)) {
  console.error(`Member list not found: ${path.relative(rootDir, source)}`);
  process.exit(1);
}

const lines = fs
  .readFileSync(source, 'utf8')
  .replace(/^﻿/, '')
  .split(/\r?\n/)
  .filter((line) => line.trim() !== '');

const header = lines[0].split('\t').map((h) => h.trim().toLowerCase());
const column = (name) => {
  const index = header.indexOf(name);
  if (index === -1) {
    console.error(`Missing column "${name}" in ${path.relative(rootDir, source)}`);
    process.exit(1);
  }
  return index;
};
// Optional columns may be missing in older member lists – every row then reads as empty
const optionalColumn = (name) => header.indexOf(name);

const firstNameCol = column('jméno');
const lastNameCol = column('příjmení');
const nicknameCol = column('nickname');
const createdAtCol = column('datum přidání');
const adminCol = column('administrátor');
const externCol = column('externista');
const formerCol = optionalColumn('bývalý');
const groupCols = Object.entries(GROUP_COLUMNS).map(([name, id]) => [column(name), id]);

const isYes = (value) => (value ?? '').trim().toUpperCase() === 'ANO';

// Demo build is downloadable JavaScript – keep only the surname initial and a fixed number
// of asterisks, so neither the surname nor its length leaks ("Horák" → "H*****")
const SURNAME_MASK = '*****';
const maskSurname = (lastName) => (lastName ? `${[...lastName][0]}${SURNAME_MASK}` : '');

// Nicknames identify members in the app (mentions) – compare without case and diacritics
const nicknameKey = (nickname) => nickname.normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase().trim();

// The "administrátor" column becomes the "Správa souboru" mandate (seeded in mock-mandates.ts)
const ensembleAdminIds = [];

const members = lines.slice(1).map((line, index) => {
  const cells = line.split('\t').map((c) => c.trim());
  const id = index + 1;
  const firstName = cells[firstNameCol];
  const lastName = maskSurname(cells[lastNameCol]);
  if (isYes(cells[adminCol])) ensembleAdminIds.push(id);
  return {
    id,
    ensembleId: 1,
    userId: id,
    firstName,
    lastName,
    nickname: cells[nicknameCol] || `${firstName} ${lastName}`.trim(),
    groupIds: groupCols.filter(([col]) => isYes(cells[col])).map(([, groupId]) => groupId),
    // The "externista" column marks a person outside the ensemble (Member.isExternal)
    ...(isYes(cells[externCol]) ? { isExternal: true } : {}),
    // The "bývalý" column marks a former member – kept for history, without access (isActive = false)
    isActive: !isYes(cells[formerCol]),
    createdAt: cells[createdAtCol] || new Date().toISOString().slice(0, 10),
  };
});

const byNickname = new Map();
for (const member of members) {
  const key = nicknameKey(member.nickname);
  byNickname.set(key, [...(byNickname.get(key) ?? []), member]);
}
const duplicates = [...byNickname.values()].filter((group) => group.length > 1);
if (duplicates.length) {
  console.error('Nicknames must be unique – fix these rows in the member list:');
  for (const group of duplicates) {
    console.error(`  "${group[0].nickname}": rows ${group.map((m) => m.id + 1).join(', ')}`);
  }
  process.exit(1);
}

const output = `// GENERATED by scripts/import-members.mjs from dev/local/clenove.tsv – do not edit, do not commit.
import { Member } from '../../../core/models/member.model';

export const MOCK_MEMBERS: Member[] = ${JSON.stringify(members, null, 2)};

// Members with the "Správa souboru" mandate in the demo data
export const MOCK_ENSEMBLE_ADMIN_IDS: number[] = ${JSON.stringify(ensembleAdminIds)};
`;

fs.writeFileSync(target, output);
console.log(`Imported ${members.length} members to ${path.relative(rootDir, target)}`);
