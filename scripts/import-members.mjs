// Converts the local (unversioned) member list dev/local/clenove.tsv into
// frontend/src/app/features/members/data/mock-members.local.ts, which replaces
// the fictional mock members in the `demo` build configuration.
// Both files are git-ignored – real names must never reach the repository.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');

const source = path.resolve(rootDir, process.argv[2] ?? 'dev/local/clenove.tsv');
const target = path.join(rootDir, 'frontend', 'src', 'app', 'features', 'members', 'data', 'mock-members.local.ts');

// Column header → group id (must match frontend/src/app/core/data/mock-groups.ts)
const GROUP_COLUMNS = {
  'výbor': 1,
  'taneční': 2,
  'muzika': 3,
  'kluci': 4,
  'holky': 5,
  'malá vonica': 6,
  'sklad': 7,
};

if (!fs.existsSync(source)) {
  console.error(`Member list not found: ${path.relative(rootDir, source)}`);
  process.exit(1);
}

const lines = fs
  .readFileSync(source, 'utf8')
  .replace(/^﻿/, '')
  .split(/\r?\n/)
  .filter((line) => line.trim() !== '');

const header = lines[0].split('\t').map((h) => h.trim().toLowerCase());
const column = (name) => {
  const index = header.indexOf(name);
  if (index === -1) {
    console.error(`Missing column "${name}" in ${path.relative(rootDir, source)}`);
    process.exit(1);
  }
  return index;
};

const firstNameCol = column('jméno');
const lastNameCol = column('příjmení');
const nicknameCol = column('nickname');
const createdAtCol = column('datum přidání');
const adminCol = column('administrátor');
const groupCols = Object.entries(GROUP_COLUMNS).map(([name, id]) => [column(name), id]);

const isYes = (value) => (value ?? '').trim().toUpperCase() === 'ANO';

const members = lines.slice(1).map((line, index) => {
  const cells = line.split('\t').map((c) => c.trim());
  const id = index + 1;
  const firstName = cells[firstNameCol];
  const lastName = cells[lastNameCol];
  return {
    id,
    ensembleId: 1,
    userId: id,
    firstName,
    lastName,
    nickname: cells[nicknameCol] || `${firstName} ${lastName}`.trim(),
    groupIds: groupCols.filter(([col]) => isYes(cells[col])).map(([, groupId]) => groupId),
    isAdmin: isYes(cells[adminCol]),
    isActive: true,
    createdAt: cells[createdAtCol] || new Date().toISOString().slice(0, 10),
  };
});

const output = `// GENERATED by scripts/import-members.mjs from dev/local/clenove.tsv – do not edit, do not commit.
import { Member } from '../../../core/models/member.model';

export const MOCK_MEMBERS: Member[] = ${JSON.stringify(members, null, 2)};
`;

fs.writeFileSync(target, output);
console.log(`Imported ${members.length} members to ${path.relative(rootDir, target)}`);
